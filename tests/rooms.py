import json
def wall_rows(n, w=32): return ["#"+"."*(w-2)+"#" for _ in range(n)]
R1 = ["#"*32] + wall_rows(3) + ["#..........b...................#"] + wall_rows(5) + \
     ["#...............====...........#", "#..............................#", "#..............................#",
      "#.........====................." + ".",
      "#.............................." + ".",
      "#..P....C......................" + ".",
      "##########################GGG###", "##########################GGG###"]
R2 = ["#"*32] + wall_rows(9) + ["#.............======...........#", "#..............................#", "#..............................#",
      "......====..............====....", "................................", "................c...............",
      "#"*32, "#"*32]
R3 = ["#"*32] + wall_rows(12) + ["."*31+"#"]*3 + ["#########......................#"] + wall_rows(6) + \
     ["#.........j....................#"] + wall_rows(2) + \
     ["#..###########.................#"] + wall_rows(4) + ["."*31+"#"]*2 + \
     ["."*12 + "^"*19 + "#"] + ["#"*32, "#"*32]
R4 = ["#"*32] + wall_rows(5) + ["#...H..........................#", "#.######.......................#"] + wall_rows(2) + \
     ["#.......===........j...........#", "#..............................#", "#..............................#",
      "............====................", "................................", "..........^^^^^^^^.......c......",
      "#"*32, "#"*32]
R5 = ["##########################...###", "#.........................===..#", "#..............................#", "#..............................#",
      "#.........................===..#", "#..............................#", "#..............................#",
      "#.........................===..#", "#..............................#", "#..............................#",
      "#.........................===..#", "#..............................#", "#..............................#",
      "#.........................===...", "#...............................", "#..a....a.............L.........",
      "####....########################", "####....########################"]
R6 = ["####....########################", "####DDDD########################"] + wall_rows(11) + \
     ["#======..................======#", "#..............................#", "#.......................B......#", "#"*32, "#"*32]
rooms = [  # name, purpose, col, row (global, top-left), rows
  ("Belfry Landing", "Safe start: move, jump, attack, see the bell and the locked grate", 0, 0, R1),
  ("Flooded Nave", "One Brine Crab in the open: learn spacing", 32, 0, R2),
  ("Gutter Shaft", "Descent over spikes with one Knell Jelly: learn its timing", 64, 0, R3),
  ("Choir Gallery", "Crab, jelly and spikes together, optional ledge with a Brass Lung", 32, 18, R4),
  ("Bell Ropes", "Winch opens the grate shortcut; the glowing drop leads to the bell", 0, 18, R5),
  ("The Undertoll", "Boss arena", 0, 36, R6),
]
W, H = 96, 54
grid = [["#"]*W for _ in range(H)]
ok = True
for name, _, cx, cy, rows in rooms:
    for i, r in enumerate(rows):
        if len(r) != 32: print("BAD WIDTH", name, i, len(r), r); ok = False
    for i, r in enumerate(rows):
        for j, ch in enumerate(r): grid[cy+i][cx+j] = ch
print(name, "rows", [len(r[4]) for r in rooms])
print("heights", [len(r[4]) for r in rooms])
# openings line up: check a few known shared edges are open on both sides
def g(x, y): return grid[y][x]
for y in (13, 14, 15):
    print("R1|R2", g(31, y), g(32, y), " R2|R3", g(63, y), g(64, y))
for y in (31, 32, 33):
    print("R4|R3", g(63, y), g(64, y), " R5|R4", g(31, y), g(32, y))
print("gate", [g(x, 16) for x in (26, 27, 28)], "R5 top", [g(x, 18) for x in (26, 27, 28)])
print("boss hole", [g(x, 34) for x in range(4, 8)], [g(x, 36) for x in range(4, 8)], [g(x, 37) for x in range(4, 8)])
json.dump({"W": W, "H": H, "rows": ["".join(r) for r in grid], "rooms": [[n, p, cx, cy, 32, len(rows)] for n, p, cx, cy, rows in rooms]}, open("rooms.json", "w"))
print("ok" if ok else "FIX WIDTHS")
