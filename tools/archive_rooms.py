"""Generate Assets/Scripts/Core/ArchiveData.cs, the Sounding Archive map (chapter III).

Five corridor rooms sit side by side on the lower band; the optional Map Loft sits above Listening Cells and is
reached by a stack of one-way shelves two tiles apart (the controller rises 3.26 tiles). Every required step on
the main path is flat. Run: python tools/archive_rooms.py
"""

import json
from pathlib import Path

W, H, CELL_W, CELL_H = 160, 36, 32, 18
grid = [["#"] * W for _ in range(H)]
specs = []


def room(name, purpose, col, row):
    for y in range(row + 1, row + CELL_H - 2):
        for x in range(col + 1, col + CELL_W - 1):
            grid[y][x] = "."
    specs.append((name, purpose, col, row, CELL_W, CELL_H))
    return lambda x, y, ch: grid[row + y].__setitem__(col + x, ch)


def passage(boundary_x, row, ch_left=".", ch_right="."):
    # Rooms meet on a two-tile wall; open the bottom three rows of it.
    for y in range(row + 13, row + 16):
        grid[y][boundary_x - 1] = ch_left
        grid[y][boundary_x] = ch_right


desk = room("Receiving Desk", "Light the green lamp. The empty drum rings twice: jump each ripple.", 0, 18)
stacks = room("Silt Stacks", "The moth marks where it will land. Step off the mark, then strike.", 32, 18)
cells = room("Listening Cells", "Jump both rings. The widow sags after its echo: strike then.", 64, 18)
loft = room("Map Loft", "Engraved pipe diagrams. Drop back down when you are done.", 64, 0)
chute = room("Return Chute", "Strike the counterweight. Up rides the chute to the lamp.", 96, 18)
choir = room("Recording Choir", "Only the real Archivist swings its clapper.", 128, 18)

desk(3, 15, "P")
desk(7, 15, "C")
desk(18, 15, "o")

stacks(20, 7, "m")
for x in range(6, 11):
    stacks(x, 12, "=")
for x in range(22, 27):
    stacks(x, 12, "=")

cells(22, 15, "w")
for y in range(14, -1, -2):
    for x in range(3, 6):
        cells(x, y, "=")
# The shelf stack goes through the ceiling into the Map Loft floor.
for x in range(3, 6):
    loft(x, 17, ".")
    loft(x, 16, "=")
loft(24, 15, "R")
for x in range(12, 17):
    loft(x, 12, "=")

chute(10, 15, "L")
chute(20, 15, "O")
chute(26, 7, "m")

for y in range(1, 16):
    choir(1, y, "D")
choir(16, 15, "Z")
choir(29, 15, "E")

passage(32, 18)
passage(64, 18)
passage(96, 18)
passage(128, 18, ch_left="K")

rows = ["".join(r) for r in grid]
assert all(len(r) == W for r in rows)
out = ["// Generated by tools/archive_rooms.py.", "namespace DrownedBell.Core", "{", "    internal static class ArchiveData", "    {",
       "        public static readonly (string Name, string Purpose, int Col, int Row, int W, int H)[] Rooms =", "        {"]
out += [f"            ({json.dumps(n)}, {json.dumps(p)}, {c}, {r}, {w}, {h})," for n, p, c, r, w, h in specs]
out += ["        };", "", "        public static readonly string[] Rows =", "        {"]
out += [f'            "{r}",' for r in rows]
out += ["        };", "    }", "}", ""]
(Path(__file__).resolve().parents[1] / "Assets/Scripts/Core/ArchiveData.cs").write_text("\n".join(out), encoding="utf-8")
print("\n".join(rows))
