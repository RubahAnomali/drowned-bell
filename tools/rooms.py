"""Generate the checked-in Unity blockout from authored room geometry."""

import json
from pathlib import Path


class Room:
    def __init__(self, name, purpose, x, y, width=32, height=18):
        self.spec = (name, purpose, x, y, width, height)
        self.rows = [["#"] * width for _ in range(height)]
        self.paint(1, 1, width - 2, height - 3, ".")

    def paint(self, x, y, width, height, tile):
        assert x >= 0 and x + width <= len(self.rows[0])
        assert y >= 0 and y + height <= len(self.rows)
        for row in self.rows[y:y + height]:
            row[x:x + width] = [tile] * width

    def mark(self, x, y, marker):
        self.paint(x, y, 1, 1, marker)

    def passage(self, x, y=13):
        self.paint(x, y, 1, 3, ".")


landing = Room("Belfry Landing", "Teach movement and introduce the tide lamp and locked grate", 0, 0)
landing.mark(3, 15, "P")
landing.mark(8, 15, "C")
landing.mark(11, 4, "b")
landing.paint(13, 14, 3, 2, "#")
landing.paint(16, 11, 4, 1, "=")
landing.paint(26, 16, 3, 2, "G")
landing.passage(31)

nave = Room("Flooded Nave", "Learn to bait and punish one Brine Crab", 32, 0)
nave.passage(0)
nave.passage(31)
nave.mark(16, 15, "c")
for x in (6, 23):
    nave.paint(x, 13, 4, 1, "=")

ripple = Room("Ripple Walk", "Read a bell wind-up and jump its floor wave", 64, 0)
ripple.passage(0)
ripple.passage(31)
ripple.paint(7, 14, 3, 2, "#")
ripple.mark(17, 9, "W")

shaft = Room("Gutter Shaft", "Follow the ledges down past a Knell Jelly", 96, 0, height=36)
shaft.passage(0)
shaft.paint(0, 16, 9, 1, "#")
shaft.paint(6, 22, 10, 1, "=")
shaft.paint(2, 28, 10, 1, "=")
shaft.mark(16, 23, "j")
shaft.paint(13, 33, 18, 1, "^")
shaft.passage(0, 31)

gallery = Room("Choir Gallery", "Combine waves, enemy spacing and a pit; climb for the Brass Lung", 32, 18, width=64)
gallery.passage(0)
gallery.passage(63)
gallery.mark(49, 15, "c")
gallery.mark(37, 9, "W")
gallery.paint(24, 16, 3, 1, "^")
gallery.mark(25, 9, "j")
gallery.paint(13, 13, 4, 1, "=")
gallery.paint(9, 10, 4, 1, "=")
gallery.paint(4, 7, 5, 1, "#")
gallery.mark(6, 6, "H")

ropes = Room("Bell Ropes", "Open the return shortcut and rest before the marked drop", 0, 18)
ropes.passage(31)
ropes.paint(26, 0, 3, 1, ".")
for row in range(0, 15, 2):
    ropes.mark(28 if row % 4 == 0 else 26, row, "=")
ropes.mark(27, 0, "=")
ropes.mark(22, 15, "L")
ropes.mark(3, 15, "a")
ropes.mark(8, 15, "a")
ropes.paint(4, 16, 4, 2, ".")

arena = Room("The Undertoll", "Read the slam and jump its shockwave under pressure", 0, 36)
arena.paint(4, 0, 4, 1, ".")
arena.paint(4, 1, 4, 1, "D")
for ledge, base in ((1, 1), (25, 29)):
    arena.paint(ledge, 13, 6, 1, "=")
    arena.paint(base, 14, 2, 2, "#")
arena.mark(24, 15, "B")

rooms = [landing, nave, ripple, shaft, gallery, ropes, arena]
grid = [["#"] * 128 for _ in range(54)]
specs = []
for room in rooms:
    name, purpose, x, y, width, height = room.spec
    for offset, row in enumerate(room.rows):
        grid[y + offset][x:x + width] = row
    specs.append(f"            ({json.dumps(name)}, {json.dumps(purpose)}, {x}, {y}, {width}, {height}),")

header = """// Generated by tools/rooms.py.
namespace DrownedBell.Core
{
    internal static class RoomData
    {
        public static readonly (string Name, string Purpose, int Col, int Row, int W, int H)[] Rooms =
        {
"""
rows = [f'            "{"".join(row)}",' for row in grid]
output = header + "\n".join(specs) + "\n        };\n\n        public static readonly string[] Rows =\n        {\n"
output += "\n".join(rows) + "\n        };\n    }\n}\n"
(Path(__file__).resolve().parents[1] / "Assets/Scripts/Core/RoomData.cs").write_text(output, encoding="utf-8")
